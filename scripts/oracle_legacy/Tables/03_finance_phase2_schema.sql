-- =====================================================================
-- Soorty ERP - Finance Module - PHASE 2 schema (Oracle 19c)
-- Run AFTER 01 and 02, as the APXWASTAGE owner. Run once. TEST first.
-- Creates: wst_djn_fin_voucher, wst_djn_fin_voucher_line,
--          wst_djn_fin_advance, wst_djn_fin_receivable,
--          wst_djn_fin_allocation, wst_djn_fin_event_log
--          + "posted rows cannot change" triggers.
-- Customer = the vendor on the Sales Order (wst_djn_vendors.vendor_id).
-- =====================================================================

-- 1. Voucher header. Posted vouchers are never edited; a mistake is
--    corrected by a reversal voucher (status flips POSTED -> REVERSED only).
CREATE TABLE apxwastage.wst_djn_fin_voucher (
    voucher_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    voucher_no          VARCHAR2(40)  NOT NULL,
    type_code           VARCHAR2(10)  NOT NULL,
    division            VARCHAR2(30)  NOT NULL,
    voucher_date        DATE          NOT NULL,
    party_id            NUMBER,
    narration           VARCHAR2(300),
    source_type         VARCHAR2(20)  NOT NULL,
    source_id           VARCHAR2(40),
    amount              NUMBER(18,2)  NOT NULL,
    status              VARCHAR2(10)  DEFAULT 'POSTED' NOT NULL,
    reverses_voucher_id NUMBER,
    created_by          VARCHAR2(150),
    created_at          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT wst_djn_fin_vch_no_uq     UNIQUE (voucher_no),
    CONSTRAINT wst_djn_fin_vch_status_ck CHECK (status IN ('POSTED','REVERSED')),
    CONSTRAINT wst_djn_fin_vch_src_ck    CHECK (source_type IN ('GATEPASS','ADVANCE','OPENING','MANUAL')),
    CONSTRAINT wst_djn_fin_vch_amt_ck    CHECK (amount > 0),
    CONSTRAINT wst_djn_fin_vch_rev_fk    FOREIGN KEY (reverses_voucher_id) REFERENCES apxwastage.wst_djn_fin_voucher (voucher_id)
);
CREATE INDEX apxwastage.wst_djn_fin_vch_party_ix  ON apxwastage.wst_djn_fin_voucher (party_id, voucher_date);
CREATE INDEX apxwastage.wst_djn_fin_vch_source_ix ON apxwastage.wst_djn_fin_voucher (source_type, source_id);

-- 2. Voucher lines (double entry). Never updated or deleted.
CREATE TABLE apxwastage.wst_djn_fin_voucher_line (
    line_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    voucher_id  NUMBER        NOT NULL,
    line_no     NUMBER(4)     NOT NULL,
    account_id  NUMBER        NOT NULL,
    party_id    NUMBER,
    debit       NUMBER(18,2)  DEFAULT 0 NOT NULL,
    credit      NUMBER(18,2)  DEFAULT 0 NOT NULL,
    CONSTRAINT wst_djn_fin_vln_vch_fk  FOREIGN KEY (voucher_id) REFERENCES apxwastage.wst_djn_fin_voucher (voucher_id),
    CONSTRAINT wst_djn_fin_vln_acc_fk  FOREIGN KEY (account_id) REFERENCES apxwastage.wst_djn_fin_account (account_id),
    CONSTRAINT wst_djn_fin_vln_amt_ck  CHECK (debit >= 0 AND credit >= 0 AND (debit = 0 OR credit = 0) AND (debit + credit) > 0),
    CONSTRAINT wst_djn_fin_vln_uq      UNIQUE (voucher_id, line_no)
);
CREATE INDEX apxwastage.wst_djn_fin_vln_acc_ix ON apxwastage.wst_djn_fin_voucher_line (account_id);
CREATE INDEX apxwastage.wst_djn_fin_vln_pty_ix ON apxwastage.wst_djn_fin_voucher_line (party_id);

-- 3. Customer advances (prepayments, and opening balances at cut-over).
--    remaining is reduced by dispatch knock-off and restored by reversal.
CREATE TABLE apxwastage.wst_djn_fin_advance (
    advance_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    party_id      NUMBER        NOT NULL,
    division      VARCHAR2(30)  NOT NULL,
    advance_date  DATE          NOT NULL,
    kind          VARCHAR2(10)  NOT NULL,
    pay_mode      VARCHAR2(10),
    reference     VARCHAR2(100),
    amount        NUMBER(18,2)  NOT NULL,
    remaining     NUMBER(18,2)  NOT NULL,
    voucher_id    NUMBER        NOT NULL,
    status        VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
    created_by    VARCHAR2(150),
    created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT wst_djn_fin_adv_status_ck CHECK (status IN ('ACTIVE','REVERSED')),
    CONSTRAINT wst_djn_fin_adv_kind_ck  CHECK (kind IN ('RECEIPT','OPENING')),
    CONSTRAINT wst_djn_fin_adv_mode_ck  CHECK (pay_mode IS NULL OR pay_mode IN ('CASH','BANK')),
    CONSTRAINT wst_djn_fin_adv_amt_ck   CHECK (amount > 0),
    CONSTRAINT wst_djn_fin_adv_rem_ck   CHECK (remaining >= 0 AND remaining <= amount),
    CONSTRAINT wst_djn_fin_adv_vch_fk   FOREIGN KEY (voucher_id) REFERENCES apxwastage.wst_djn_fin_voucher (voucher_id)
);
CREATE INDEX apxwastage.wst_djn_fin_adv_party_ix ON apxwastage.wst_djn_fin_advance (party_id, advance_date);

-- 4. Receivables (the sale a dispatch creates). Prepaid model: always
--    settled in full in the same transaction; table kept so credit sales
--    can be switched on later without a redesign.
CREATE TABLE apxwastage.wst_djn_fin_receivable (
    receivable_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    party_id      NUMBER        NOT NULL,
    division      VARCHAR2(30)  NOT NULL,
    source_type   VARCHAR2(20)  NOT NULL,
    source_id     VARCHAR2(40)  NOT NULL,
    doc_date      DATE          NOT NULL,
    amount        NUMBER(18,2)  NOT NULL,
    settled       NUMBER(18,2)  DEFAULT 0 NOT NULL,
    status        VARCHAR2(10)  DEFAULT 'OPEN' NOT NULL,
    voucher_id    NUMBER        NOT NULL,
    created_by    VARCHAR2(150),
    created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT wst_djn_fin_rcv_status_ck CHECK (status IN ('OPEN','SETTLED','REVERSED')),
    CONSTRAINT wst_djn_fin_rcv_amt_ck    CHECK (amount > 0 AND settled >= 0 AND settled <= amount),
    CONSTRAINT wst_djn_fin_rcv_src_uq    UNIQUE (source_type, source_id, party_id),
    CONSTRAINT wst_djn_fin_rcv_vch_fk    FOREIGN KEY (voucher_id) REFERENCES apxwastage.wst_djn_fin_voucher (voucher_id)
);
CREATE INDEX apxwastage.wst_djn_fin_rcv_party_ix ON apxwastage.wst_djn_fin_receivable (party_id, doc_date);

-- 5. Allocations: which advance paid which receivable.
CREATE TABLE apxwastage.wst_djn_fin_allocation (
    allocation_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    receivable_id NUMBER        NOT NULL,
    advance_id    NUMBER        NOT NULL,
    amount        NUMBER(18,2)  NOT NULL,
    voucher_id    NUMBER        NOT NULL,
    status        VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
    created_by    VARCHAR2(150),
    created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT wst_djn_fin_alc_status_ck CHECK (status IN ('ACTIVE','REVERSED')),
    CONSTRAINT wst_djn_fin_alc_amt_ck    CHECK (amount > 0),
    CONSTRAINT wst_djn_fin_alc_rcv_fk    FOREIGN KEY (receivable_id) REFERENCES apxwastage.wst_djn_fin_receivable (receivable_id),
    CONSTRAINT wst_djn_fin_alc_adv_fk    FOREIGN KEY (advance_id)    REFERENCES apxwastage.wst_djn_fin_advance (advance_id),
    CONSTRAINT wst_djn_fin_alc_vch_fk    FOREIGN KEY (voucher_id)    REFERENCES apxwastage.wst_djn_fin_voucher (voucher_id)
);
CREATE INDEX apxwastage.wst_djn_fin_alc_rcv_ix ON apxwastage.wst_djn_fin_allocation (receivable_id);
CREATE INDEX apxwastage.wst_djn_fin_alc_adv_ix ON apxwastage.wst_djn_fin_allocation (advance_id);

-- 6. Event log: one row per Gate Pass event. A finance failure never stops
--    the Gate Pass; it is recorded here as FAILED for the Super Admin to retry.
CREATE TABLE apxwastage.wst_djn_fin_event_log (
    event_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    event_type   VARCHAR2(20)  NOT NULL,
    source_id    VARCHAR2(40)  NOT NULL,
    division     VARCHAR2(30),
    event_date   DATE,
    status       VARCHAR2(10)  NOT NULL,
    attempts     NUMBER(4)     DEFAULT 1 NOT NULL,
    message      VARCHAR2(500),
    voucher_ids  VARCHAR2(200),
    actor        VARCHAR2(150),
    created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at   TIMESTAMP,
    CONSTRAINT wst_djn_fin_evt_uq        UNIQUE (event_type, source_id),
    CONSTRAINT wst_djn_fin_evt_type_ck   CHECK (event_type IN ('GP_POSTED','GP_CANCELLED')),
    CONSTRAINT wst_djn_fin_evt_status_ck CHECK (status IN ('POSTED','FAILED','SKIPPED'))
);
CREATE INDEX apxwastage.wst_djn_fin_evt_status_ix ON apxwastage.wst_djn_fin_event_log (status, created_at);

-- ---------------------------------------------------------------------
-- Immutability: posted accounting rows cannot be changed or removed.
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER apxwastage.wst_djn_fin_vln_lock
BEFORE UPDATE OR DELETE ON apxwastage.wst_djn_fin_voucher_line
BEGIN
    RAISE_APPLICATION_ERROR(-20911, 'Voucher lines are permanent: post a reversal voucher instead.');
END;
/

CREATE OR REPLACE TRIGGER apxwastage.wst_djn_fin_vch_lock
BEFORE UPDATE OR DELETE ON apxwastage.wst_djn_fin_voucher
FOR EACH ROW
BEGIN
    IF DELETING THEN
        RAISE_APPLICATION_ERROR(-20912, 'Vouchers cannot be deleted: post a reversal voucher instead.');
    END IF;
    -- Only allowed change: POSTED -> REVERSED, everything else identical.
    IF :OLD.status <> 'POSTED' OR :NEW.status <> 'REVERSED'
       OR :OLD.voucher_no <> :NEW.voucher_no
       OR :OLD.type_code  <> :NEW.type_code
       OR :OLD.division   <> :NEW.division
       OR :OLD.voucher_date <> :NEW.voucher_date
       OR :OLD.amount     <> :NEW.amount
       OR NVL(:OLD.party_id, -1) <> NVL(:NEW.party_id, -1)
       OR NVL(:OLD.narration, ' ') <> NVL(:NEW.narration, ' ')
       OR :OLD.source_type <> :NEW.source_type
       OR NVL(:OLD.source_id, ' ') <> NVL(:NEW.source_id, ' ')
       OR NVL(:OLD.reverses_voucher_id, -1) <> NVL(:NEW.reverses_voucher_id, -1) THEN
        RAISE_APPLICATION_ERROR(-20913, 'A posted voucher cannot be edited: post a reversal voucher instead.');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER apxwastage.wst_djn_fin_adv_nodel
BEFORE DELETE ON apxwastage.wst_djn_fin_advance
BEGIN
    RAISE_APPLICATION_ERROR(-20914, 'Customer advances cannot be deleted.');
END;
/

CREATE OR REPLACE TRIGGER apxwastage.wst_djn_fin_rcv_nodel
BEFORE DELETE ON apxwastage.wst_djn_fin_receivable
BEGIN
    RAISE_APPLICATION_ERROR(-20915, 'Receivables cannot be deleted.');
END;
/

CREATE OR REPLACE TRIGGER apxwastage.wst_djn_fin_alc_nodel
BEFORE DELETE ON apxwastage.wst_djn_fin_allocation
BEGIN
    RAISE_APPLICATION_ERROR(-20916, 'Allocations cannot be deleted.');
END;
/

