-- ---------------------------------------------------------------------
-- 1. Chart of accounts
--    IS_POSTING = 0 -> group head (cannot receive postings)
--    SYSTEM_KEY     -> stable name the posting rules point to
--    IS_LOCKED = 1  -> system head: code/type/key fixed, cannot deactivate
-- ---------------------------------------------------------------------
CREATE TABLE apxwastage.wst_djn_fin_account (
    account_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    account_code      VARCHAR2(10)  NOT NULL,
    account_name      VARCHAR2(150) NOT NULL,
    account_type      VARCHAR2(10)  NOT NULL,
    parent_id         NUMBER,
    is_posting        NUMBER(1)     DEFAULT 1 NOT NULL,
    is_locked         NUMBER(1)     DEFAULT 0 NOT NULL,
    system_key        VARCHAR2(40),
    is_active         NUMBER(1)     DEFAULT 1 NOT NULL,
    created_by        VARCHAR2(150),
    created_date      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    last_updated_by   VARCHAR2(150),
    last_updated_date TIMESTAMP,
    CONSTRAINT wst_djn_fin_account_code_uq   UNIQUE (account_code),
    CONSTRAINT wst_djn_fin_account_key_uq    UNIQUE (system_key),
    CONSTRAINT wst_djn_fin_account_type_ck   CHECK (account_type IN ('ASSET','LIABILITY','INCOME','EXPENSE','EQUITY')),
    CONSTRAINT wst_djn_fin_account_post_ck   CHECK (is_posting IN (0,1)),
    CONSTRAINT wst_djn_fin_account_lock_ck   CHECK (is_locked  IN (0,1)),
    CONSTRAINT wst_djn_fin_account_act_ck    CHECK (is_active  IN (0,1)),
    CONSTRAINT wst_djn_fin_account_parent_fk FOREIGN KEY (parent_id) REFERENCES apxwastage.wst_djn_fin_account (account_id)
);

-- ---------------------------------------------------------------------
-- 2. Settings (key / value, typed and validated in the application)
-- ---------------------------------------------------------------------
CREATE TABLE apxwastage.wst_djn_fin_setting (
    setting_key    VARCHAR2(60)  PRIMARY KEY,
    setting_value  VARCHAR2(500),
    value_type     VARCHAR2(10)  NOT NULL,
    options        VARCHAR2(200),
    description    VARCHAR2(300),
    is_editable    NUMBER(1)     DEFAULT 1 NOT NULL,
    updated_by     VARCHAR2(150),
    updated_at     TIMESTAMP,
    CONSTRAINT wst_djn_fin_setting_type_ck CHECK (value_type IN ('TEXT','INT','DECIMAL','YN','CHOICE','INTLIST')),
    CONSTRAINT wst_djn_fin_setting_edit_ck CHECK (is_editable IN (0,1))
);

-- ---------------------------------------------------------------------
-- 3. Accounting periods. A month with no row is OPEN.
-- ---------------------------------------------------------------------
CREATE TABLE apxwastage.wst_djn_fin_period (
    period_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    division       VARCHAR2(30)  NOT NULL,
    period_year    NUMBER(4)     NOT NULL,
    period_month   NUMBER(2)     NOT NULL,
    status         VARCHAR2(10)  DEFAULT 'OPEN' NOT NULL,
    locked_by      VARCHAR2(150),
    locked_at      TIMESTAMP,
    reopened_by    VARCHAR2(150),
    reopened_at    TIMESTAMP,
    reopen_reason  VARCHAR2(300),
    CONSTRAINT wst_djn_fin_period_uq        UNIQUE (division, period_year, period_month),
    CONSTRAINT wst_djn_fin_period_month_ck  CHECK (period_month BETWEEN 1 AND 12),
    CONSTRAINT wst_djn_fin_period_status_ck CHECK (status IN ('OPEN','LOCKED'))
);

-- ---------------------------------------------------------------------
-- 4. Document numbering counters (used from Phase 2)
-- ---------------------------------------------------------------------
CREATE TABLE apxwastage.wst_djn_fin_sequence (
    type_code   VARCHAR2(10) NOT NULL,
    division    VARCHAR2(30) NOT NULL,
    seq_year    NUMBER(4)    NOT NULL,
    last_no     NUMBER(10)   DEFAULT 0 NOT NULL,
    CONSTRAINT wst_djn_fin_sequence_pk PRIMARY KEY (type_code, division, seq_year)
);

-- ---------------------------------------------------------------------
-- 5. Voucher types
-- ---------------------------------------------------------------------
CREATE TABLE apxwastage.wst_djn_fin_voucher_type (
    type_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    type_code           VARCHAR2(10)  NOT NULL,
    type_name           VARCHAR2(80)  NOT NULL,
    prefix              VARCHAR2(10)  NOT NULL,
    is_system           NUMBER(1)     DEFAULT 0 NOT NULL,
    is_active           NUMBER(1)     DEFAULT 1 NOT NULL,
    approval_threshold  NUMBER(18,2),
    CONSTRAINT wst_djn_fin_vtype_code_uq UNIQUE (type_code)
);

-- ---------------------------------------------------------------------
-- 6. Posting rules: which account KEYS an event debits and credits
-- ---------------------------------------------------------------------
CREATE TABLE apxwastage.wst_djn_fin_posting_rule (
    rule_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    event_code         VARCHAR2(30)  NOT NULL,
    description        VARCHAR2(200),
    debit_account_key  VARCHAR2(40)  NOT NULL,
    credit_account_key VARCHAR2(40)  NOT NULL,
    is_active          NUMBER(1)     DEFAULT 1 NOT NULL,
    updated_by         VARCHAR2(150),
    updated_at         TIMESTAMP,
    CONSTRAINT wst_djn_fin_prule_event_uq UNIQUE (event_code),
    CONSTRAINT wst_djn_fin_prule_sides_ck CHECK (debit_account_key <> credit_account_key)
);

-- ---------------------------------------------------------------------
-- 7. Finance audit log. Separate from wst_djn_audit_log ON PURPOSE:
--    the Wastage Audit Log screen lists every table in that log, so
--    finance entries stored there would be visible to any user holding
--    the audit_log permission. This table is only ever read by the
--    Super Admin finance screens.
--    Append-only: the trigger below rejects UPDATE and DELETE.
-- ---------------------------------------------------------------------
CREATE TABLE apxwastage.wst_djn_fin_audit_log (
    log_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    event_time   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    actor        VARCHAR2(150),
    event_type   VARCHAR2(20)  NOT NULL,
    table_name   VARCHAR2(40),
    record_id    VARCHAR2(60),
    action       VARCHAR2(20),
    field_name   VARCHAR2(60),
    old_value    VARCHAR2(1900),
    new_value    VARCHAR2(1900),
    request_path VARCHAR2(300),
    ip_address   VARCHAR2(120),
    CONSTRAINT wst_djn_fin_audit_type_ck CHECK (event_type IN ('CHANGE','DENIED','ACCESS'))
);

CREATE INDEX apxwastage.wst_djn_fin_audit_time_ix ON apxwastage.wst_djn_fin_audit_log (event_time);
CREATE INDEX apxwastage.wst_djn_fin_audit_type_ix ON apxwastage.wst_djn_fin_audit_log (event_type, event_time);

CREATE OR REPLACE TRIGGER apxwastage.wst_djn_fin_audit_lock
BEFORE UPDATE OR DELETE ON apxwastage.wst_djn_fin_audit_log
BEGIN
    RAISE_APPLICATION_ERROR(-20901, 'wst_djn_fin_audit_log is append-only: rows cannot be changed or deleted.');
END;
/

