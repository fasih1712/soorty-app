-- A posted voucher can only change POSTED -> REVERSED, nothing else.
CREATE OR REPLACE FUNCTION trg_fin_voucher_lock() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'ORA-20912: Vouchers cannot be deleted: post a reversal voucher instead.';
    END IF;
    IF OLD.status <> 'POSTED' OR NEW.status <> 'REVERSED'
       OR OLD.voucher_no   <> NEW.voucher_no
       OR OLD.type_code    <> NEW.type_code
       OR OLD.division     <> NEW.division
       OR OLD.voucher_date <> NEW.voucher_date
       OR OLD.amount       <> NEW.amount
       OR OLD.party_id            IS DISTINCT FROM NEW.party_id
       OR OLD.narration           IS DISTINCT FROM NEW.narration
       OR OLD.source_type  <> NEW.source_type
       OR OLD.source_id           IS DISTINCT FROM NEW.source_id
       OR OLD.reverses_voucher_id IS DISTINCT FROM NEW.reverses_voucher_id THEN
        RAISE EXCEPTION 'ORA-20913: A posted voucher cannot be edited: post a reversal voucher instead.';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER wst_djn_fin_vch_lock BEFORE UPDATE OR DELETE ON wst_djn_fin_voucher
    FOR EACH ROW EXECUTE FUNCTION trg_fin_voucher_lock();


