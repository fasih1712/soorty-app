-- =====================================================================
-- Soorty ERP (wastage + finance) -- PostgreSQL schema
-- Converted from the Oracle scripts in Tables/*.sql plus every column the
-- application code reads/writes. Run once on an EMPTY database:
--     psql -U soorty -d soorty -f postgres/01_schema.sql
--     psql -U soorty -d soorty -f postgres/02_seed.sql
-- (docker-compose runs both automatically on the first start of the DB.)
--
-- Type mapping used:
--   NUMBER (ids, counts)      -> BIGINT / INTEGER
--   NUMBER(1) flags           -> SMALLINT
--   NUMBER(p,s)               -> NUMERIC(p,s)
--   VARCHAR2(n)               -> VARCHAR(n)
--   DATE (has a time part!)   -> TIMESTAMP(0)
--   IDENTITY                  -> GENERATED BY DEFAULT AS IDENTITY
-- =====================================================================

SET client_min_messages = warning;

-- ---------------------------------------------------------------------
-- Oracle-compatible helper functions used by the application SQL
-- (TRUNC on dates, ADD_MONTHS, TO_DATE on an already-typed date).
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION trunc(d timestamp) RETURNS timestamp
    LANGUAGE sql IMMUTABLE AS $$ SELECT date_trunc('day', d) $$;
CREATE OR REPLACE FUNCTION trunc(d date) RETURNS timestamp
    LANGUAGE sql IMMUTABLE AS $$ SELECT d::timestamp $$;
CREATE OR REPLACE FUNCTION trunc(d timestamp, fmt text) RETURNS timestamp
    LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE upper(fmt)
        WHEN 'MM' THEN date_trunc('month', d)   WHEN 'MON' THEN date_trunc('month', d)
        WHEN 'MONTH' THEN date_trunc('month', d)
        WHEN 'YYYY' THEN date_trunc('year', d)  WHEN 'YEAR' THEN date_trunc('year', d)
        WHEN 'Y' THEN date_trunc('year', d)     WHEN 'Q' THEN date_trunc('quarter', d)
        WHEN 'HH' THEN date_trunc('hour', d)    WHEN 'HH24' THEN date_trunc('hour', d)
        WHEN 'MI' THEN date_trunc('minute', d)
        ELSE date_trunc('day', d) END $$;
CREATE OR REPLACE FUNCTION trunc(d date, fmt text) RETURNS timestamp
    LANGUAGE sql IMMUTABLE AS $$ SELECT trunc(d::timestamp, fmt) $$;
CREATE OR REPLACE FUNCTION add_months(d timestamp, n integer) RETURNS timestamp
    LANGUAGE sql IMMUTABLE AS $$ SELECT d + make_interval(months => n) $$;
CREATE OR REPLACE FUNCTION add_months(d date, n integer) RETURNS timestamp
    LANGUAGE sql IMMUTABLE AS $$ SELECT d::timestamp + make_interval(months => n) $$;
CREATE OR REPLACE FUNCTION to_date(d date, fmt text) RETURNS date
    LANGUAGE sql IMMUTABLE AS $$ SELECT d $$;
CREATE OR REPLACE FUNCTION to_date(d timestamp, fmt text) RETURNS date
    LANGUAGE sql IMMUTABLE AS $$ SELECT d::date $$;

-- Current app user for audit columns (was SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'))
CREATE OR REPLACE FUNCTION app_user(fallback text DEFAULT 'DIRECT_DB_EDIT') RETURNS text
    LANGUAGE sql STABLE AS $$
    SELECT COALESCE(NULLIF(current_setting('app.client_identifier', true), ''), fallback) $$;

-- Generic audit trigger: CREATED_BY/CREATED_DATE on insert, LAST_UPDATED_* always.
CREATE OR REPLACE FUNCTION trg_audit_cols() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v text := app_user(COALESCE(TG_ARGV[0], 'DIRECT_DB_EDIT'));
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.created_by := v;
        NEW.created_date := LOCALTIMESTAMP(0);
    ELSE
        NEW.created_by := OLD.created_by;
        NEW.created_date := OLD.created_date;
    END IF;
    NEW.last_updated_by := v;
    NEW.last_updated_date := LOCALTIMESTAMP(0);
    RETURN NEW;
END $$;

-- Sales: numeric CREATED_BY is a user id, so only the other three are stamped.
CREATE OR REPLACE FUNCTION trg_audit_cols_sales() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v text := app_user();
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.created_date := LOCALTIMESTAMP(0);
    ELSE
        NEW.created_date := OLD.created_date;
    END IF;
    NEW.last_updated_by := v;
    NEW.last_updated_date := LOCALTIMESTAMP(0);
    RETURN NEW;
END $$;

-- Raises "ORA-<code>: <message>" so the app's error handling sees the same text as before.
CREATE OR REPLACE FUNCTION trg_block() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '%', TG_ARGV[0] USING ERRCODE = 'P0001';
END $$;


